		inline std::vector<std::byte> encode_utf16_bytes(const std::u32string& cps, bool big_endian) {
			std::u16string units = codepoints_to_utf16(cps);
			std::vector<std::byte> out(units.size() * 2);
			for (std::size_t i = 0; i < units.size(); ++i) {
				unsigned char hi = static_cast<unsigned char>((units[i] >> 8) & 0xFF);
				unsigned char lo = static_cast<unsigned char>(units[i] & 0xFF);
				out[i * 2 + 0] = static_cast<std::byte>(big_endian ? hi : lo);
				out[i * 2 + 1] = static_cast<std::byte>(big_endian ? lo : hi);
			}
			return out;
		}
		inline std::vector<std::byte> encode_utf32_bytes(const std::u32string& cps, bool big_endian) {
			std::vector<std::byte> out(cps.size() * 4);
			for (std::size_t i = 0; i < cps.size(); ++i) {
				char32_t cp = cps[i];
				unsigned char b[4] = {
					static_cast<unsigned char>((cp >> 24) & 0xFF),
					static_cast<unsigned char>((cp >> 16) & 0xFF),
					static_cast<unsigned char>((cp >> 8) & 0xFF),
					static_cast<unsigned char>(cp & 0xFF)
				};
				for (int k = 0; k < 4; ++k)
					out[i * 4 + k] = static_cast<std::byte>(big_endian ? b[k] : b[3 - k]);
			}
			return out;
		}
		inline std::vector<std::byte> encode_ascii_bytes(const std::u32string& cps) {
			std::vector<std::byte> out;
			out.reserve(cps.size());
			for (char32_t cp : cps) {
				out.push_back(static_cast<std::byte>(cp <= 0x7F ? static_cast<unsigned char>(cp) : '?'));
			}
			return out;
		}
		inline std::vector<std::byte> encode_single_byte_identity(const std::u32string& cps) {
			std::vector<std::byte> out;
			out.reserve(cps.size());
			for (char32_t cp : cps)
				out.push_back(static_cast<std::byte>(cp <= 0xFF ? static_cast<unsigned char>(cp) : '?'));
			return out;
		}
